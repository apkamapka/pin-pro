type Dict = typeof dict.pl;

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useI18n = create<I18nState>()(
  persist(
    (set) => ({
      lang: "pl",
      setLang: (lang) => set({ lang }),
    }),
    { name: "serwismap-lang" },
  ),
);

export function useT(): Dict {
  const lang = useI18n((s) => s.lang);
  return dict[lang] as Dict;
}
